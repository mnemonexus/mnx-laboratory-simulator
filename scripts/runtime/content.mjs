// Ship the framework's catalogue packs and curated definitions as pack assets.
//
// The add-on reads them at start-up through mnx.asset (src/runtime/content.ts), so the content
// stays out of the 8 MiB code file. content.build.json (beside manifest.json) says which packs
// (packages/pack-*/pack.json, catalogue/*.json, definitions/*.labx.json) go into which asset.
// This script writes them, with the index the add-on reads first:
//
//   assets/content/index.json, assets/content/<bundle>.json   the pack's assets (kit check, pack, dev)
//   public/assets/content/…                                   the same files, for npm run dev and the standalone build
//
// Every file it writes must be declared in manifest.json's "assets"; it says which are missing.
//
//   npm run content                                    regenerate what changed (runs before dev, build and the addon scripts)
//   npm run content -- --check                         fail if a generated file is stale or undeclared
//   node scripts/runtime/content.mjs --addon <folder>  another add-on's build (its content.build.json and manifest.json)
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const packages = join(root, 'packages')
/** Must match CONTENT_FORMAT in src/runtime/content.ts. */
const FORMAT = 'mnx-lab-content/1'
const ASSET_DIR = 'assets/content'
const INDEX = `${ASSET_DIR}/index.json`
const KINDS = ['purposes', 'operations', 'techniques', 'equipment', 'substances', 'preparations', 'skills', 'rules', 'models']
const GENERATED = 'Generated by scripts/runtime/content.mjs from packages/pack-*/ and content.build.json. Do not edit: run "npm run content".'

const args = process.argv.slice(2)
const check = args.includes('--check')
const addonArg = args.includes('--addon') ? args[args.indexOf('--addon') + 1] : undefined
const addonDir = addonArg ? resolve(process.cwd(), addonArg) : root
const isRoot = resolve(addonDir) === resolve(root)
const show = (p) => relative(root, p).replace(/\\/g, '/') || '.'
const errors = []
const warnings = []
const read = (p) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n')

// ---- The build manifest ----
const buildFile = join(addonDir, 'content.build.json')
if (!existsSync(buildFile)) {
  console.error(`${show(buildFile)} is missing: it says which content packs this add-on ships.`)
  process.exit(1)
}
const buildText = read(buildFile)
const build = JSON.parse(buildText)
const bundles = Array.isArray(build.bundles) ? build.bundles : []
if (!bundles.length) errors.push(`${show(buildFile)}: "bundles" must list at least one {"file", "packs"}.`)
const bundleOf = new Map() // pack id → bundle file
let rest // the bundle that takes every pack not named
const files = new Set()
for (const [i, b] of bundles.entries()) {
  const where = `${show(buildFile)} bundles[${i}]`
  if (typeof b?.file !== 'string' || !/^[a-z0-9][a-z0-9-]*\.json$/.test(b.file) || b.file === 'index.json') {
    errors.push(`${where}: "file" must be a lower-case name like "chemistry.json" (not index.json).`)
    continue
  }
  if (files.has(b.file)) errors.push(`${where}: "${b.file}" is listed twice.`)
  files.add(b.file)
  if (!Array.isArray(b.packs)) errors.push(`${where}: "packs" must be a list of pack ids (or "*").`)
  for (const id of Array.isArray(b.packs) ? b.packs : []) {
    if (id === '*') {
      if (rest) errors.push(`${where}: only one bundle can take the remaining packs ("*").`)
      rest = b.file
    } else if (bundleOf.has(id)) errors.push(`${where}: pack "${id}" is already in ${bundleOf.get(id)}.`)
    else bundleOf.set(id, b.file)
  }
}

// ---- The packs on disk, core first ----
const dirs = readdirSync(packages, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name.startsWith('pack-') && existsSync(join(packages, d.name, 'pack.json')))
  .map((d) => d.name)
  .sort((a, b) => (a === 'pack-core' ? -1 : b === 'pack-core' ? 1 : a.localeCompare(b)))

const hash = createHash('sha256').update(`${FORMAT}\ncontent.build.json\n${buildText}`)
const packs = [] // { id, dir, content, definitions }
for (const dir of dirs) {
  const base = join(packages, dir)
  const packText = read(join(base, 'pack.json'))
  hash.update(`${dir}/pack.json\n${packText}`)
  const content = { pack: JSON.parse(packText) }
  for (const kind of KINDS) {
    const file = join(base, 'catalogue', `${kind}.json`)
    if (!existsSync(file)) continue
    const text = read(file)
    hash.update(`${dir}/${kind}\n${text}`)
    content[kind] = JSON.parse(text)
  }
  const id = content.pack.id
  if (packs.some((p) => p.id === id)) errors.push(`packages/${dir}: pack id "${id}" is also used by packages/${packs.find((p) => p.id === id).dir}.`)
  const definitions = []
  const defs = join(base, 'definitions')
  if (existsSync(defs)) {
    for (const f of readdirSync(defs).filter((n) => n.endsWith('.labx.json')).sort()) {
      const text = read(join(defs, f))
      hash.update(`${dir}/${f}\n${text}`)
      definitions.push({ pack: id, file: f, json: JSON.parse(text) })
    }
  }
  packs.push({ id, dir, content, definitions })
}
const source = hash.digest('hex').slice(0, 16)

// ---- Which packs ship, and where ----
for (const id of bundleOf.keys()) if (!packs.some((p) => p.id === id)) warnings.push(`${show(buildFile)} names pack "${id}", which no packages/pack-*/pack.json declares.`)
const shipped = []
const left = []
for (const p of packs) {
  const file = bundleOf.get(p.id) ?? rest
  if (file) shipped.push({ ...p, file })
  else left.push(p.id)
}
for (const p of shipped) {
  for (const dep of Array.isArray(p.content.pack.dependsOn) ? p.content.pack.dependsOn : []) {
    if (!shipped.some((q) => q.id === dep)) errors.push(`Pack "${p.id}" depends on "${dep}", which ${show(buildFile)} does not ship.`)
  }
}
if (errors.length) {
  for (const e of errors) console.error(`error: ${e}`)
  process.exit(1)
}

// ---- The files ----
const list = (items) => (items.length ? `[\n${items.map((x) => JSON.stringify(x)).join(',\n')}\n]` : '[]')
const outputs = new Map() // asset path → text
for (const b of bundles) {
  const path = `${ASSET_DIR}/${b.file}`
  const inBundle = shipped.filter((p) => p.file === b.file)
  // One pack or definition per line, so a change shows as a small diff.
  outputs.set(
    path,
    `{"$comment":${JSON.stringify(GENERATED)},"format":${JSON.stringify(FORMAT)},"bundle":${JSON.stringify(path)},` +
      `"packs":${list(inBundle.map((p) => p.content))},"definitions":${list(inBundle.flatMap((p) => p.definitions))}}\n`,
  )
}
const index = {
  $comment: GENERATED,
  format: FORMAT,
  addon: build.addon ?? null,
  source,
  // The add-on installs the packs in this order (core first), whichever bundle holds them.
  packs: shipped.map((p) => ({ id: p.id, bundle: `${ASSET_DIR}/${p.file}`, definitions: p.definitions.length })),
  bundles: bundles.map((b) => `${ASSET_DIR}/${b.file}`),
}
outputs.set(INDEX, `${JSON.stringify(index, null, 2)}\n`)

// Where the files go: the add-on's own assets, and (for this folder's add-on) the dev server's copy.
const targets = [addonDir, ...(isRoot ? [join(root, 'public')] : [])]

// ---- The add-on manifest must declare them ----
const manifestFile = join(addonDir, 'manifest.json')
const manifest = existsSync(manifestFile) ? JSON.parse(read(manifestFile)) : {}
const declared = new Set((Array.isArray(manifest.assets) ? manifest.assets : []).map((a) => a?.logicalPath))
const undeclared = [...outputs.keys()].filter((p) => !declared.has(p))
const orphans = [...declared].filter((p) => typeof p === 'string' && p.startsWith(`${ASSET_DIR}/`) && !outputs.has(p))
const manifestProblems = [
  ...undeclared.map((p) => `${show(manifestFile)} does not declare "${p}". Add { "logicalPath": "${p}", "mimeType": "application/json" } to its "assets".`),
  ...orphans.map((p) => `${show(manifestFile)} declares "${p}", which ${show(buildFile)} no longer builds. Remove it from "assets".`),
]
if (build.addon && manifest.id && build.addon !== manifest.id) warnings.push(`${show(buildFile)} is for "${build.addon}" but ${show(manifestFile)} is "${manifest.id}".`)
if (left.length) console.log(`Not shipped in this add-on (no bundle takes them): ${left.join(', ')}.`)

const legacy = join(root, 'src/runtime/content.gen.ts')
const summary = `${shipped.length} packs, ${shipped.reduce((n, p) => n + p.definitions.length, 0)} definitions, ${bundles.length} bundles`

if (check) {
  const stale = []
  for (const dir of targets) {
    for (const [path, text] of outputs) {
      const file = join(dir, path)
      if (!existsSync(file) || readFileSync(file, 'utf8') !== text) stale.push(show(file))
    }
  }
  for (const w of warnings) console.warn(`warning: ${w}`)
  if (isRoot && existsSync(legacy)) console.warn('warning: src/runtime/content.gen.ts is no longer used (the content ships as assets). Run "npm run content" to remove it.')
  if (stale.length || manifestProblems.length) {
    if (stale.length) console.error(`The content assets are stale (${stale.join(', ')}). Run "npm run content".`)
    for (const m of manifestProblems) console.error(`error: ${m}`)
    process.exit(1)
  }
  console.log(`The content assets are up to date (${summary}).`)
  process.exit(0)
}

const written = []
for (const dir of targets) {
  const out = join(dir, ASSET_DIR)
  mkdirSync(out, { recursive: true })
  for (const [path, text] of outputs) {
    const file = join(dir, path)
    if (!process.argv.includes('--force') && existsSync(file) && readFileSync(file, 'utf8') === text) continue
    writeFileSync(file, text)
    written.push(show(file))
  }
  // Bundles this build no longer makes.
  for (const name of readdirSync(out)) {
    if (name.endsWith('.json') && !outputs.has(`${ASSET_DIR}/${name}`)) {
      rmSync(join(out, name))
      written.push(`${show(join(out, name))} (removed)`)
    }
  }
}
// The content used to be compiled into the code (src/runtime/content.gen.ts).
if (isRoot && existsSync(legacy)) {
  rmSync(legacy)
  written.push('src/runtime/content.gen.ts (removed)')
}
for (const w of warnings) console.warn(`warning: ${w}`)
for (const m of manifestProblems) console.warn(`warning: ${m}`)
if (written.length) console.log(`Wrote the content assets (${summary}): ${written.join(', ')}.`)
