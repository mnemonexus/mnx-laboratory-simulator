// Generate the Equipment Master Catalogue and the Technique → Experiment matrix from the packs, so
// the reference documents never drift from the data (master-plan 12 §11, 06 §9.2).
//
//   node scripts/docs/catalogue-docs.mjs           write docs/framework/catalogue/*.gen.md
//   node scripts/docs/catalogue-docs.mjs --check   fail if they are stale
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const packages = join(root, 'packages')
const OUT = join(root, 'docs/framework/catalogue')
const read = (p) => JSON.parse(readFileSync(p, 'utf8'))

const packDirs = readdirSync(packages, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name.startsWith('pack-') && existsSync(join(packages, d.name, 'pack.json')))
  .map((d) => d.name)
  .sort((a, b) => (a === 'pack-core' ? -1 : b === 'pack-core' ? 1 : a.localeCompare(b)))

const packs = []
const equipment = new Map()
const techniques = new Map()
const operations = new Map()
const definitions = []
for (const dir of packDirs) {
  const base = join(packages, dir)
  const pack = read(join(base, 'pack.json'))
  packs.push(pack)
  const list = (kind) => (existsSync(join(base, 'catalogue', `${kind}.json`)) ? read(join(base, 'catalogue', `${kind}.json`)) : [])
  for (const e of list('equipment')) equipment.set(e.id, { ...e, pack: pack.id })
  for (const t of list('techniques')) techniques.set(t.id, { ...t, pack: pack.id })
  for (const o of list('operations')) operations.set(o.id, { ...o, pack: pack.id })
  const defs = join(base, 'definitions')
  if (!existsSync(defs)) continue
  for (const f of readdirSync(defs).filter((n) => n.endsWith('.labx.json')).sort()) definitions.push({ pack: pack.id, json: read(join(defs, f)) })
}

// What each definition uses: technique and operation steps, and every equipment id it names anywhere.
const usesEquipment = new Map()
const usesTechnique = new Map()
const usesOperation = new Map()
const add = (map, key, def) => {
  if (!map.has(key)) map.set(key, new Set())
  map.get(key).add(def)
}
function walk(node, def) {
  if (Array.isArray(node)) return node.forEach((n) => walk(n, def))
  if (!node || typeof node !== 'object') {
    if (typeof node === 'string' && equipment.has(node)) add(usesEquipment, node, def)
    return
  }
  if (typeof node.ref === 'string' && node.kind === 'technique') add(usesTechnique, node.ref, def)
  if (typeof node.ref === 'string' && node.kind === 'operation') add(usesOperation, node.ref, def)
  for (const v of Object.values(node)) walk(v, def)
}
// A technique's own steps count too: a definition using it uses what it uses.
const techniqueEquipment = new Map()
for (const t of techniques.values()) {
  const probe = new Map()
  const inner = (node) => {
    if (Array.isArray(node)) return node.forEach(inner)
    if (!node || typeof node !== 'object') {
      if (typeof node === 'string' && equipment.has(node)) probe.set(node, true)
      return
    }
    for (const v of Object.values(node)) inner(v)
  }
  inner(t.steps ?? [])
  techniqueEquipment.set(t.id, [...probe.keys()])
}
const titleOf = new Map()
for (const d of definitions) {
  const id = d.json.id
  const title = typeof d.json.title === 'string' && !d.json.title.includes('{{') ? d.json.title : (d.json.variants?.[0]?.title ?? d.json.variants?.[0]?.values?.title ?? id)
  titleOf.set(id, title)
  walk(d.json, id)
}
for (const [tid, defs] of usesTechnique) for (const e of techniqueEquipment.get(tid) ?? []) for (const def of defs) add(usesEquipment, e, def)

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const purposesOf = (e) => [...new Set((e.capabilities ?? []).map((c) => c.purpose).concat(e.purposes ?? []))].filter(Boolean)
const defList = (set) => (set ? [...set].sort().map((d) => `\`${d}\``).join(', ') : '—')
const header = (title, what) =>
  `# ${title}\n\n> Generated by \`node scripts/docs/catalogue-docs.mjs\` from \`packages/pack-*/\`. Do not edit by hand; change the catalogue or the definitions and regenerate.\n\n${what}\n\n`

let eq = header(
  'Equipment master catalogue',
  `Every equipment entry in the catalogue packs (${equipment.size} entries over ${packs.length} packs), with its level, kind, purposes and the curated definitions that use it (directly, or through a technique's steps). Class entries describe what a role may be filled with; model entries are concrete items. Equipment that no definition uses yet is still listed.`,
)
for (const pack of packs) {
  const rows = [...equipment.values()].filter((e) => e.pack === pack.id)
  if (!rows.length) continue
  eq += `## ${esc(pack.label)} (\`${pack.id}\`)\n\n| Id | Label | Level | Kind | Purposes | Used by |\n|---|---|---|---|---|---|\n`
  for (const e of rows.sort((a, b) => a.id.localeCompare(b.id)))
    eq += `| \`${e.id}\` | ${esc(e.label)} | ${esc(e.level)} | ${esc(e.kind)} | ${esc(purposesOf(e).join(', '))} | ${defList(usesEquipment.get(e.id))} |\n`
  eq += '\n'
}

let tm = header(
  'Technique → experiment matrix',
  `Which curated definitions use each technique (${techniques.size} techniques) and each kernel operation (${operations.size} operations) as procedure steps, over ${definitions.length} definition files. Variants of a definition share its row. Titles with variant placeholders show the first variant's title.`,
)
tm += `## Techniques\n\n| Technique | Label | Purposes | Definitions |\n|---|---|---|---|\n`
for (const t of [...techniques.values()].sort((a, b) => a.id.localeCompare(b.id)))
  tm += `| \`${t.id}\` | ${esc(t.label)} | ${esc((t.purposes ?? []).join(', '))} | ${defList(usesTechnique.get(t.id))} |\n`
tm += `\n## Operations\n\n| Operation | Label | Definitions using it directly |\n|---|---|---|\n`
for (const o of [...operations.values()].sort((a, b) => a.id.localeCompare(b.id)))
  tm += `| \`${o.id}\` | ${esc(o.label)} | ${usesOperation.get(o.id)?.size ?? 0} |\n`
tm += `\n## Definitions\n\n| Definition | Pack | Title | Techniques |\n|---|---|---|---|\n`
for (const d of definitions) {
  const used = [...usesTechnique].filter(([, s]) => s.has(d.json.id)).map(([k]) => `\`${k}\``)
  tm += `| \`${d.json.id}\` | ${d.pack} | ${esc(titleOf.get(d.json.id))} | ${used.join(', ') || '—'} |\n`
}

const outputs = [
  [join(OUT, 'equipment-catalogue.gen.md'), eq],
  [join(OUT, 'technique-matrix.gen.md'), tm],
]
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([p, text]) => !existsSync(p) || readFileSync(p, 'utf8') !== text)
  if (stale.length) {
    console.error(`Stale: ${stale.map(([p]) => p).join(', ')}. Run "node scripts/docs/catalogue-docs.mjs".`)
    process.exit(1)
  }
  console.log('Catalogue documents are up to date.')
} else {
  for (const [p, text] of outputs) writeFileSync(p, text)
  console.log(`Wrote ${outputs.length} documents: ${equipment.size} equipment, ${techniques.size} techniques, ${operations.size} operations, ${definitions.length} definitions.`)
}
