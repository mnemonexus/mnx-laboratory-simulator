// Compile the lightmap bake worker into a string module:
// src/three/lab/bake.worker.gen.ts.
//
// The MnemoNexus sandbox only runs *classic* workers made from blob: URLs, and
// the add-on kit bundles with Bun, which has no equivalent of Vite's
// `?worker&inline`. So the worker is compiled here into plain JavaScript that
// bakeRunner.ts turns into a blob. Vite (`npm run dev`) and the kit (check,
// pack) then both import an ordinary module, and ship the same worker.
//
//   npm run worker              regenerate if bake.ts or bake.worker.ts changed
//   npm run worker -- --check   fail if the generated file is stale
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '../..')
const lab = join(root, 'src/three/lab')
const SOURCES = ['bake.worker.ts', 'bake.ts']
const OUT = join(lab, 'bake.worker.gen.ts')

// Line endings normalised so a checkout with CRLF hashes the same.
const hash = createHash('sha256')
for (const name of SOURCES) hash.update(readFileSync(join(lab, name), 'utf8').replace(/\r\n/g, '\n'))
const marker = `// source-hash: ${hash.digest('hex').slice(0, 16)}`
const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
const fresh = current.includes(marker)

if (process.argv.includes('--check')) {
  if (!fresh) {
    console.error('src/three/lab/bake.worker.gen.ts is stale. Run "npm run worker".')
    process.exit(1)
  }
  console.log('bake.worker.gen.ts is up to date.')
  process.exit(0)
}
if (fresh && !process.argv.includes('--force')) process.exit(0)

const { build } = await import('vite')
const result = await build({
  configFile: false,
  publicDir: false,
  logLevel: 'warn',
  build: {
    write: false,
    emptyOutDir: false,
    minify: true,
    target: 'es2020',
    lib: { entry: join(lab, 'bake.worker.ts'), formats: ['iife'], name: 'labBakeWorker' },
  },
})
const outputs = (Array.isArray(result) ? result : [result]).flatMap((r) => r.output)
const chunks = outputs.filter((o) => o.type === 'chunk')
if (chunks.length !== 1) throw new Error(`Expected one worker chunk, got ${chunks.length}.`)

writeFileSync(
  OUT,
  `// Generated by scripts/addon/worker.mjs from ${SOURCES.join(' and ')}. Do not edit: run "npm run worker".\n` +
    `${marker}\n` +
    `export const BAKE_WORKER_SOURCE = ${JSON.stringify(chunks[0].code)}\n`,
)
console.log(`Wrote src/three/lab/bake.worker.gen.ts (${(chunks[0].code.length / 1024).toFixed(1)} KiB).`)
