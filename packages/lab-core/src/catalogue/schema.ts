// Schemas for catalogue entries in packs (validated with code prefix CAT).
import { DEFINITION_DEFS } from '../format/schema.ts'
import { CATALOGUE_REF, PURPOSE_ID, SEMVER } from '../format/formats.ts'
import { any, arr, bool, enm, int, map, num, obj, ref, type Schema, type SchemaDefs, str, union } from '../schema/schema.ts'

const status = enm(['stable', 'experimental', 'stub'])
const catRef = (description?: string) => str({ pattern: CATALOGUE_REF, description })
const purposeId = () => str({ pattern: PURPOSE_ID })
const quantity = (dimension?: string[]) => str({ format: 'quantity', formatArgs: dimension ? { dimension } : undefined })
const provenance = obj({ 'references?': arr(str()), 'review?': enm(['pending', 'reviewed']), 'notes?': str() })

const paramSpec: Schema = obj({
  type: enm(['quantity', 'number', 'integer', 'text', 'boolean', 'enum', 'material', 'container', 'equipment', 'place', 'list', 'record', 'any']),
  'dimension?': str(),
  'values?': arr(str()),
  'items?': ref('ParamSpec'),
  'default?': any(),
  'required?': bool(),
  'description?': str(),
})

const roleSpec = obj({
  kind: enm(['equipment', 'container', 'material', 'place']),
  'requires?': map(str()),
  'prefer?': arr(catRef()),
  'count?': str({ format: 'expression' }),
  'description?': str(),
})

const criterion = obj({
  id: str({ pattern: '^[a-z0-9]+(-[a-z0-9]+)*$' }),
  statement: str(),
  check: str({ format: 'predicate' }),
  'severity?': enm(['critical', 'major', 'minor']),
  'skills?': arr(catRef()),
  'feedbackKind?': enm(['procedural', 'calculation', 'measurement', 'design', 'interpretive', 'practice', 'safety']),
})

export const CATALOGUE_DEFS: SchemaDefs = { ...DEFINITION_DEFS, ParamSpec: paramSpec }

