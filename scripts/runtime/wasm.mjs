import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
const crate = 'packages/lab-science-rust'
execFileSync('cargo', ['build', '--manifest-path', `${crate}/Cargo.toml`, '--target', 'wasm32-unknown-unknown', '--release'], { stdio: 'inherit' })
const binary = readFileSync(`${crate}/target/wasm32-unknown-unknown/release/lab_science.wasm`)
mkdirSync('src/runtime', { recursive: true })
// Embed verified build bytes: the classic-script pack needs no fetch or module loader.
const generated = `// Generated by npm run science:build. Do not hand-edit.\nexport const SCIENCE_WASM_BASE64 = '${binary.toString('base64')}'\nexport const SCIENCE_WASM_SHA256 = '${createHash('sha256').update(binary).digest('hex')}'\n`
const path = 'src/runtime/science.wasm.gen.ts'
if (!existsSync(path) || readFileSync(path, 'utf8') !== generated) writeFileSync(path, generated)
console.log(`Rust/Wasm scientific core: ${binary.length} bytes`)
