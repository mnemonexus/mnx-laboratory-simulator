// Exports the focused bench tools (packages/lab-core/src/bench) as one self-contained ES module for a
// host that runs them without the whole lab: the bench code from lab-core plus the catalogue slice it
// needs, embedded as data. MnemoNexus vendors this file for its "From Laboratory Simulator" learning
// tools, so the tools and the full practical share one science.
//
//   node scripts/bench/export.mjs [--root <tree>] [--out <file.js>]
//
// --root reads lab-core and the packs from another tree (for example a clean `git archive` of a
// commit), so the export matches a commit exactly; it defaults to this repository. --out defaults to
// dist/learning-tools/lab-bench.js. A matching .d.ts is written beside it.
import { build } from 'esbuild'
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = resolve(HERE, '..', '..')
const arg = (name) => {
  const i = process.argv.indexOf(name)
  return i > 0 ? process.argv[i + 1] : undefined
}
const root = resolve(arg('--root') ?? REPO)
const out = resolve(arg('--out') ?? join(REPO, 'dist', 'learning-tools', 'lab-bench.js'))

const { loadAllPacks } = await import(pathToFileURL(join(root, 'apps', 'cli', 'fs-packs.ts')).href)
const { benchPackSlice } = await import(pathToFileURL(join(root, 'packages', 'lab-core', 'src', 'bench', 'slice.ts')).href)
const { BENCH_VERSION, BENCH_CHECKER_VERSION } = await import(pathToFileURL(join(root, 'packages', 'lab-core', 'src', 'bench', 'bench.ts')).href)
const packs = loadAllPacks()
const slice = benchPackSlice(packs)

function git(...args) {
  try {
    return execFileSync('git', args, { cwd: REPO, encoding: 'utf8' }).trim()
  } catch {
    return ''
  }
}
const commit = arg('--commit') ?? git('rev-parse', 'HEAD')
const dirty = root === REPO ? git('status', '--porcelain', '--', 'packages/lab-core/src', 'packages/pack-core', 'packages/pack-chemistry', 'packages/pack-aqueous') : ''
const manifest = JSON.parse(readFileSync(join(root, 'manifest.json'), 'utf8'))

const tmp = mkdtempSync(join(tmpdir(), 'lab-bench-'))
try {
  const slicePath = join(tmp, 'slice.json')
  writeFileSync(slicePath, JSON.stringify(slice))
  const entry = [
    `import { createBench } from ${JSON.stringify(join(root, 'packages', 'lab-core', 'src', 'bench', 'index.ts').replaceAll('\\', '/'))}`,
    `import slice from ${JSON.stringify(slicePath.replaceAll('\\', '/'))}`,
    `export const source = ${JSON.stringify({ addon: manifest.id, addonVersion: manifest.version, commit, engineVersion: BENCH_VERSION, checkerVersion: BENCH_CHECKER_VERSION, packs: slice.map((p) => `${p.pack.id}@${p.pack.version}`) })}`,
    'let bench',
    '/** The bench over the embedded catalogue slice, built on first use. */',
    'export function loadBench() { return (bench ??= createBench(slice)) }',
  ].join('\n')
  const result = await build({
    stdin: { contents: entry, resolveDir: tmp, sourcefile: 'lab-bench-entry.js', loader: 'js' },
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2020', write: false, minify: true, legalComments: 'none',
    absWorkingDir: root,
  })
  const header = [
    '/* eslint-disable */',
    '// GENERATED by the Laboratory Simulator add-on (scripts/bench/export.mjs). Do not edit: change',
    '// packages/lab-core/src/bench there and export again.',
    `// Source: ${manifest.id} ${manifest.version}, commit ${commit || 'unknown'}${dirty ? ' (with uncommitted changes)' : ''}; bench engine ${BENCH_VERSION}, checker ${BENCH_CHECKER_VERSION}.`,
    '',
  ].join('\n')
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, header + result.outputFiles[0].text)
  writeFileSync(out.replace(/\.js$/, '.d.ts'), readFileSync(join(HERE, 'lab-bench.d.ts.txt'), 'utf8'))
  console.log(`wrote ${out} (${Math.round(Buffer.byteLength(header + result.outputFiles[0].text) / 1024)} KB, ${slice.reduce((n, p) => n + (p.substances?.length ?? 0), 0)} substances, ${slice.reduce((n, p) => n + (p.equipment?.length ?? 0), 0)} equipment)`)
} finally {
  rmSync(tmp, { recursive: true, force: true })
}
